# ----------------------------------------
# 문제 3. 이상 탐지를 다시 한다
# ----------------------------------------
# 온도의 z-점수를 (가) 표 전체 기준, (나) 같은 생산라인 기준 두 가지로 구해
# 임계값 2.5를 넘는 개수를 한 줄에 출력하세요. 표준편차는 ddof=0 입니다.
# 이어서 (나)로 걸린 행의 검사일시·생산라인·설비번호·온도를 라인 순으로 출력하고,
# 라인별 온도 평균도 출력해 근거로 삼으세요.
#


temp_mean_3 = cleaned_2["온도"].mean()  # 전체 온도 평균
temp_std_3 = cleaned_2["온도"].std(ddof=0)  # 전체 온도 표준편차
z_all_3 = (cleaned_2["온도"] - temp_mean_3) / temp_std_3  # 전체 기준 온도 z점수
line_mean_3 = cleaned_2.groupby("생산라인")["온도"].transform(
    "mean"
)  # 각 행이 속한 생산라인의 온도 평균
line_std_3 = cleaned_2.groupby("생산라인")["온도"].transform(lambda x: x.std(ddof=0))
# 각 행이 속한 생산라인의 온도 표준편차
z_line_3 = (cleaned_2["온도"] - line_mean_3) / line_std_3  # 생산라인별 기준 온도 z점수
outlier_all_3 = z_all_3.abs() > 2.5  # 전체 기준에서 이상치인지 확인
outlier_line_3 = z_line_3.abs() > 2.5  # 생산라인별 기준에서 이상치인지 확인
print(
    outlier_all_3.sum(), outlier_line_3.sum()
)  # 전체 기준 이상치 개수 0/ 라인별 기준 이상치 개수 5
print(
    cleaned_2.loc[
        outlier_line_3, ["검사일시", "생산라인", "설비번호", "온도"]
    ].sort_values("생산라인")
)
# 라인별 기준에서 걸린 행 출력
#                  검사일시 생산라인   설비번호    온도
# 30   2026-08-25 19:00  A라인  A-102  88.2
# 54   2026-08-24 08:00  A라인  A-102  87.6
# 97   2026-08-24 17:00  A라인  A-104  94.8
# 129  2026-08-26 08:00  A라인  A-101  91.5
# 69   2026-08-25 04:00  C라인  C-101  73.5
print(round(cleaned_2.groupby("생산라인")["온도"].mean(), 2))
# 생산라인별 온도 평균
# 생산라인
# A라인    73.35
# B라인    84.85
# C라인    94.57
# Name: 온도, dtype: float64

# [확인 항목]
#   - (가)는 0건이다. 멘티가 "이상 없음"이라고 판단한 이유가 여기 있다
#     전체 온도를 하나의 평균, 표준편차로 비교 -> 라인별 온도가 섞임 -> 이상값 발견 실패
#   - (나)에서는 0건이 아니다
#     5건. (가)와 달리 (나)에서는 생산라인별로 평균, 표준편차를 각각 구함
#     -> A라인 4, C라인 1의 이상값 발견 성공
#   - 걸린 값 중에 '숫자만 보면 정상 같은데 그 라인에서는 비정상'인 것이 있다. 어느 것인가
#     C라인의 73.5도. 73.5도 자체만 보면 A라인 평균인 73.35도와 비슷해서 정상적인 온도처럼 보이지만
#     C라인의 평균은 94.57도이므로 C라인에서는 비정상적인 값이라고 추정할 수 있음
#     이런 상황이라면 이상값이라고 한 번 의심해 볼 만 함!!
# ---------- 이 마지막 확인 항목이 멘티에게 전할 말 --------------


# ----------------------------------------
# 문제 4. 채우기 전에 무엇을 먼저 해야 하는가
# ----------------------------------------
# 이제 결측을 라인별 값으로 채웁니다. 그런데 순서를 조심해야 합니다.
# 문제 3에서 찾은 이상값이 아직 표 안에 있습니다. 그 상태로 라인 평균을 구하면
# 그 평균 자체가 이미 오염되어 있습니다.
#
# 라인별 온도 평균을 '이상값 포함'과 '이상값 제외' 두 가지로 구해
# 두 값과 차이를 세 칸짜리 표로 출력하세요.
# 그다음 '이상값을 뺀 라인 평균'으로 온도 결측을 채우고,
# 압력과 진동은 라인 중앙값으로 채우세요.
# 채운 뒤 남은 결측 총 개수, 라인별 온도 평균, 그리고 멘티의 라인별 온도 평균을
# 차례로 출력해 세 값을 비교하세요.

cleaned_4 = cleaned_2.copy()
# 문제 2에서 중복을 제거한 데이터를 복사
# 멘티가 작성한 코드에서는 df["진동"] = pd.to_numeric(df["진동"], errors="coerce")fh
# 진동을 숫자로 바꾸는 작업을 해줬으나
# 현재 내 파일에서는 처음처럼 원본이기 때문에 다시 to_numeric()으로 진동을 숫자로 바꾸는 작업 필요
cleaned_4["진동"] = pd.to_numeric(cleaned_4["진동"], errors="coerce")
# 진동을 숫자로 변환하고 변환할 수 없는 값은 결측치로 변경

temp_mean_before_4 = cleaned_4.groupby("생산라인")["온도"].mean()
# 온도 이상값을 포함한 상태의 라인별 온도 평균

temp_normal_4 = cleaned_4.loc[~outlier_line_3].copy()
# 문제 3에서 찾은 온도 이상값을 제외한 데이터

temp_mean_after_4 = temp_normal_4.groupby("생산라인")["온도"].mean()
# 온도 이상값을 제외한 상태의 라인별 온도 평균

print(round(temp_mean_before_4, 2))  # 이상값 포함 평균
# 생산라인
# A라인    73.35
# B라인    84.85
# C라인    94.57
# Name: 온도, dtype: float64
print(round(temp_mean_after_4, 2))  # 이상값 제외 평균
# 생산라인
# A라인    72.05
# B라인    84.85
# C라인    94.93
# Name: 온도, dtype: float64
print(round(temp_mean_before_4 - temp_mean_after_4, 2))  # 두 평균의 차이
# 생산라인
# A라인    1.30
# B라인    0.00
# C라인   -0.36
# Name: 온도, dtype: float64


cleaned_4["온도"] = cleaned_4["온도"].fillna(
    cleaned_4["생산라인"].map(temp_mean_after_4)
)
# 온도 결측치를 이상값 제외 후 구한 해당 라인의 평균으로 채움

pressure_median_4 = cleaned_4.groupby("생산라인")["압력"].transform("median")
# 각 행이 속한 라인의 압력 중앙값

vibration_median_4 = cleaned_4.groupby("생산라인")["진동"].transform("median")
# 각 행이 속한 라인의 진동 중앙값

cleaned_4["압력"] = cleaned_4["압력"].fillna(pressure_median_4)
# 압력 결측치를 같은 라인의 중앙값으로 채움

cleaned_4["진동"] = cleaned_4["진동"].fillna(vibration_median_4)
# 진동 결측치를 같은 라인의 중앙값으로 채움

print(cleaned_4[센서].isnull().sum())
# 센서별 남아 있는 결측치 개수 확인
# 온도     0
# 진동     0
# 회전수    0
# 압력     0
# dtype: int64
#
# [확인 항목]
#   - 이상값을 포함해 구한 A라인 평균과 제외하고 구한 평균이 1도 넘게 차이 난다
#   - 어느 쪽으로 채우는 것이 맞는가. 근거를 댈 수 있는가
#     A라인 중간에 이상한(높은) 온도들이 끼어 있는 것으로 확인됨
